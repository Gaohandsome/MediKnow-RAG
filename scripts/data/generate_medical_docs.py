def _sections(text: str) -> int:
    """数一下有几个 `##` 章节，用于校验内容没有退回单章版本。"""
    return text.count("\n## ")


def _normalize(text: str) -> str:
    """统一为「无 BOM、LF 换行、以单个换行结尾」，用于比对与写入。"""
    text = text.lstrip("\ufeff").replace("\r\n", "\n").replace("\r", "\n")
    return text.rstrip("\n") + "\n"


def check() -> int:
    print(f"内置 {len(DOCS)} 份文档，逐份比对 {OUT_DIR}\n")
    same = diff = missing = 0
    for name, embedded in DOCS.items():
        path = OUT_DIR / name
        want = _normalize(embedded)
        if not path.exists():
            print(f"  缺失     {name}（内置 {len(want)} 字 / {_sections(want)} 节）")
            missing += 1
            continue
        have = _normalize(path.read_text(encoding="utf-8"))
        if have == want:
            print(f"  一致     {name}（{len(have)} 字 / {_sections(have)} 节）")
            same += 1
        else:
            print(f"  不一致   {name}（磁盘 {len(have)} 字，内置 {len(want)} 字，差 {len(have) - len(want):+d}）")
            diff += 1
    print(f"\n共 {len(DOCS)} 份：一致 {same}，不一致 {diff}，缺失 {missing}")
    if diff or missing:
        print("以磁盘文件为准回写脚本：python scripts/data/generate_medical_docs.py --sync")
        return 1
    return 0


def write() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    total = 0
    for name, content in DOCS.items():
        text = _normalize(content)
        (OUT_DIR / name).write_text(text, encoding="utf-8", newline="\n")
        total += len(text)
        print(f"已写出：{name}（{len(text)} 字 / {_sections(text)} 节）")
    print(f"\n共 {len(DOCS)} 份，合计 {total} 字 → {OUT_DIR}")
    return 0


def sync() -> int:
    if not OUT_DIR.exists():
        print(f"目录不存在：{OUT_DIR}")
        return 1
    lines = ["DOCS: dict[str, str] = {"]
    for path in sorted(OUT_DIR.glob("*.md")):
        text = _normalize(path.read_text(encoding="utf-8"))
        quote = "'" * 3
        if quote in text:
            print(f"跳过 {path.name}：内容含三引号，无法安全内嵌")
            return 1
        lines.append(f'    "{path.name}": ' + quote + text + quote + ",")
    lines.append("}")
    body = "\n".join(lines)

    source = SELF.read_text(encoding="utf-8")
    head, sep, rest = source.partition(DOCS_BEGIN)
    _, sep2, tail = rest.partition(DOCS_END)
    if not sep or not sep2:
        print("脚本里找不到 DOCS-BEGIN / DOCS-END 标记，无法回写")
        return 1
    new_source = head + DOCS_BEGIN + "\n" + body + "\n" + DOCS_END + tail
    if new_source == source:
        print("脚本内嵌内容已是最新，无需改写")
        return 0
    SELF.write_text(new_source, encoding="utf-8", newline="\n")
    print(f"已按磁盘文件回写脚本：{len(lines) - 2} 份文档")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="院内知识库示例文档的生成与校验")
    group = parser.add_mutually_exclusive_group()
    group.add_argument(
        "--write",
        "--force",
        dest="write",
        action="store_true",
        help="以脚本内嵌内容为准写出 Markdown（覆盖同名文件）",
    )
    group.add_argument(
        "--sync",
        action="store_true",
        help="以 data/medical_docs 为准，回写脚本内嵌内容",
    )
    args = parser.parse_args()
    if args.write:
        return write()
    if args.sync:
        return sync()
    return check()


